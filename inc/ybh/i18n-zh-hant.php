 * YBH · 简体 → 繁体转换（T66f）
 *
 * ===================================================================
 * 为什么需要它
 * ===================================================================
 *   新增 `zh-Hant`（繁體中文）时，界面文案的中文原文本身是简体 ——
 *   如果什么都不做，繁体读者看到的是简体字（比"英文夹杂中文"更刺眼）。
 *   站点**没有** zh_TW 语言包，主题也不打算再造一份人工繁体词表，
 *   所以这里做**按需转换**：
 *     · `ybh_t()` 在 zh-Hant 下找不到显式译文 → 用本函数把中文原文转成繁体；
 *     · 主题自身的 gettext 文案（textdomain `sakurairo`）也走同一个过滤器转换；
 *     · 工作台里如果有**人工校订过的繁体译文**（覆盖层），优先级更高、会覆盖本转换结果。
 *
 * ===================================================================
 * 转换策略：先词、后字
 * ===================================================================
 *   ① **词表优先**：处理地区用词差异（设置→設定、登录→登入、保存→儲存…），
 *      这类差异靠逐字转换是转不出来的；
 *   ② **字表兜底**：把剩余的简体字按常用对应关系转成繁体 ——
 *      一字多形的情况（发→發/髮、后→後/后）在这里只取**最常用于界面文案**的那个。
 *   所以这套结果是"可读、可用"的**默认繁体**，不是最终定稿 ——
 *   最终以工作台里人工校订并批准的译文为准。
 *
 * @package SakurairoYBH
 */

