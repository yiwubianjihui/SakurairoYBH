/**
 * 简体 → 繁体（先词后字）。
 *
 * @param string $text
 * @return string
 */
function ybh_zh_hant($text)
{
    $text = (string) $text;
    if ($text === '') {
        return $text;
    }
    // ① 词表（长词优先）
    $phrases = ybh_zh_hant_phrases();
    $keys = array_keys($phrases);
    usort($keys, function ($a, $b) { return mb_strlen($b) - mb_strlen($a); });
    foreach ($keys as $k) {
        if (mb_strpos($text, $k) !== false) {
            $text = str_replace($k, $phrases[$k], $text);
        }
    }
    // ② 字表兜底
    $chars = ybh_zh_hant_chars();
    $text = strtr($text, $chars);
    return $text;
}

/**
 * 主题自身的 gettext 文案在 zh-Hant 下也做转换（核心与其它插件的文案不碰）。
 * 只在语言为 zh-Hant 且 locale 是 zh_TW 系列时生效。
 */
add_filter('gettext', 'ybh_zh_hant_gettext', 20, 3);
add_filter('ngettext', 'ybh_zh_hant_ngettext', 20, 5);
function ybh_zh_hant_gettext($translation, $text, $domain)
{
    if ($domain !== 'sakurairo' || !function_exists('ybh_current_language') || ybh_current_language() !== 'zh-Hant') {
        return $translation;
    }
    // 有官方 zh_TW 语言包给出译文时（$translation !== $text）就别动它
    if ($translation !== $text) {
        return $translation;
    }
    return ybh_zh_hant($text);
}
function ybh_zh_hant_ngettext($translation, $single, $plural, $number, $domain)
{
    if ($domain !== 'sakurairo' || !function_exists('ybh_current_language') || ybh_current_language() !== 'zh-Hant') {
        return $translation;
    }
    if ($translation !== $single && $translation !== $plural) {
        return $translation;
    }
    return ybh_zh_hant($translation);
}
